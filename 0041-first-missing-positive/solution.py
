class Solution:
    def firstMissingPositive(self, nums):
        n = len(nums)
        
        # Step 1: Place each number in its right index if 1 <= nums[i] <= n
        for i in range(n):
            while 1 <= nums[i] <= n and nums[nums[i] - 1] != nums[i]:
                target_idx = nums[i] - 1
                nums[i], nums[target_idx] = nums[target_idx], nums[i]
                
        # Step 2: Identify the first missing positive number
        for i in range(n):
            if nums[i] != i + 1:
                return i + 1
                
        # If all numbers 1 to n are present
        return n + 1
