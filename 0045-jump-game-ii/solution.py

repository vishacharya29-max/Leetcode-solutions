class Solution:
    def jump(self, nums):
        n = len(nums)
        if n <= 1:
            return 0
            
        jumps = 0
        current_end = 0
        farthest = 0
        
        # Traverse up to n - 2
        for i in range(n - 1):
            farthest = max(farthest, i + nums[i])
            
            # Reached the end of the current jump's reach
            if i == current_end:
                jumps += 1
                current_end = farthest
                
                # Early exit if the end is already reachable
                if current_end >= n - 1:
                    break
                    
        return jumps
