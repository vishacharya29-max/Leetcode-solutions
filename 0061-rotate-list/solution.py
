# Definition for singly-linked list.
# class ListNode:
#     def __init__(self, val=0, next=None):
#         self.val = val
#         self.next = next

class Solution:
    def rotateRight(self, head, k):
        if not head or not head.next or k == 0:
            return head
            
        # 1. Find the length of the list and the tail node
        length = 1
        tail = head
        while tail.next:
            tail = tail.next
            length += 1
            
        # 2. Normalize k to avoid redundant full rotations
        k %= length
        if k == 0:
            return head
            
        # 3. Connect tail to head to form a circular ring
        tail.next = head
        
        # 4. Find the new tail at (length - k - 1) steps from head
        steps_to_new_tail = length - k - 1
        new_tail = head
        for _ in range(steps_to_new_tail):
            new_tail = new_tail.next
            
        # 5. Break the cycle and return the new head
        new_head = new_tail.next
        new_tail.next = None
        
        return new_head
