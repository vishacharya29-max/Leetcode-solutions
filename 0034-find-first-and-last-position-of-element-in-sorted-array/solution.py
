class Solution:
    def searchRange(self, nums, target):
        def findBound(is_first):
            low, high = 0, len(nums) - 1
            bound = -1
            
            while low <= high:
                mid = (low + high) // 2
                
                if nums[mid] == target:
                    bound = mid
                    if is_first:
                        high = mid - 1  # Keep looking left
                    else:
                        low = mid + 1   # Keep looking right
                elif nums[mid] < target:
                    low = mid + 1
                else:
                    high = mid - 1
                    
            return bound

        start = findBound(True)
        if start == -1:
            return [-1, -1]
            
        end = findBound(False)
        return [start, end]
