class Solution:
    def countAndSay(self, n):
        s = "1"
        
        for _ in range(n - 1):
            next_s = []
            count = 1
            
            for j in range(1, len(s)):
                if s[j] == s[j - 1]:
                    count += 1
                else:
                    next_s.append(str(count))
                    next_s.append(s[j - 1])
                    count = 1
                    
            next_s.append(str(count))
            next_s.append(s[-1])
            
            s = "".join(next_s)
            
        return s
