class Solution:
    def lengthOfLastWord(self, s):
        i = len(s) - 1
        length = 0
        
        # 1. Skip any trailing spaces at the end of the string
        while i >= 0 and s[i] == ' ':
            i -= 1
            
        # 2. Count characters until the next space or start of string
        while i >= 0 and s[i] != ' ':
            length += 1
            i -= 1
            
        return length
