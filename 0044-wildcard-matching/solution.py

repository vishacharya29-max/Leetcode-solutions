class Solution:
    def isMatch(self, s, p):
        s_idx = 0
        p_idx = 0
        star_idx = -1
        s_temp = -1
        
        while s_idx < len(s):
            # Characters match or pattern has '?'
            if p_idx < len(p) and (p[p_idx] == s[s_idx] or p[p_idx] == '?'):
                s_idx += 1
                p_idx += 1
            # Wildcard '*' encountered
            elif p_idx < len(p) and p[p_idx] == '*':
                star_idx = p_idx
                s_temp = s_idx
                p_idx += 1
            # Prior '*' exists: backtrack and let '*' consume one more character
            elif star_idx != -1:
                p_idx = star_idx + 1
                s_temp += 1
                s_idx = s_temp
            # Mismatch and no '*' to backtrack to
            else:
                return False
                
        # Consume any remaining '*' characters at the end of pattern
        while p_idx < len(p) and p[p_idx] == '*':
            p_idx += 1
            
        return p_idx == len(p)
