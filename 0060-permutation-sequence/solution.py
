import math

class Solution:
    def getPermutation(self, n, k):
        numbers = [str(i) for i in range(1, n + 1)]
        fact = math.factorial(n - 1)
        k -= 1  # Convert to 0-indexed
        result = []
        
        for i in range(n - 1, 0, -1):
            idx = k // fact
            result.append(numbers.pop(idx))
            k %= fact
            fact //= i
            
        result.append(numbers[0])
        return "".join(result)
