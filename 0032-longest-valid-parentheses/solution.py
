class Solution:
    def longestValidParentheses(self, s):
        stack = [-1]
        max_len = 0
        
        for i, char in enumerate(s):
            if char == '(':
                stack.append(i)
            else:
                stack.pop()
                if not stack:
                    # Reset the base boundary index
                    stack.append(i)
                else:
                    # Valid substring length = current index - top of stack
                    max_len = max(max_len, i - stack[-1])
                    
        return max_len
